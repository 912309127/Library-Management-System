    private void addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addActionPerformed
    String title = jTextField1.getText().trim();
    String author = jTextField2.getText().trim();
    String genre = jTextField3.getText().trim();
    String barcode = jTextField4.getText().trim();

    // Also check if the text is still the default text after trimming
        if (title.isEmpty() || title.equals("Title") || 
            author.isEmpty() || author.equals("Author") ||
            genre.isEmpty() || genre.equals("Genre") ||
            barcode.isEmpty() || barcode.equals("Barcode")) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Use try-with-resources for all JDBC resources
        try (Connection conn = DBConnection.getConnection()) {
            // 1. Check for duplicate barcode
            String checkSql = "SELECT book_id FROM books WHERE barcode = ?";
            try (PreparedStatement psCheck = conn.prepareStatement(checkSql)) {
                psCheck.setString(1, barcode);
                try (ResultSet rs = psCheck.executeQuery()) {
                    if (rs.next()) {
                        JOptionPane.showMessageDialog(this, "Invalid: Barcode already exists!", "Duplicate Entry", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                }
            }

            // 2. Insert the new book (Securely using PreparedStatement)
            // Use RETURN_GENERATED_KEYS to get the new book_id for the log
            String insertSql = "INSERT INTO books(title, author, genre, barcode, status) VALUES(?,?,?,?,?)";
            try (PreparedStatement ps = conn.prepareStatement(insertSql, Statement.RETURN_GENERATED_KEYS)) {
                ps.setString(1, title);
                ps.setString(2, author);
                ps.setString(3, genre);
                ps.setString(4, barcode);
                ps.setString(5, "Available"); // Default status
                ps.executeUpdate();
                
                int newBookId = -1;
                try(ResultSet generatedKeys = ps.getGeneratedKeys()) {
                    if (generatedKeys.next()) {
                        newBookId = generatedKeys.getInt(1);
                    }
                }

                JOptionPane.showMessageDialog(this, "Book added successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                
                // LOGGING ADDED
                ActivityLog.log("BOOK_ADDED", 
                    String.format("Added Book ID: %d, Title: %s, Barcode: %s", newBookId, title, barcode));
                
                parent.loadBooks(); // Refresh the main table
                this.dispose();    // Close this frame
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_addActionPerformed

