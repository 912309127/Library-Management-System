    private void updateborrowerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateborrowerActionPerformed
    String name = jTextField1.getText().trim();
        String address = jTextField2.getText().trim();
        String contact = jTextField3.getText().trim();

        // 1. Validation
        if (name.isEmpty() || address.isEmpty() || contact.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Database UPDATE Operation
        String sql = "UPDATE borrowers SET name=?, address=?, contact=? WHERE borrower_id=?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            
            ps.setString(1, name);
            ps.setString(2, address);
            ps.setString(3, contact);
            ps.setInt(4, borrowerId);
            
            int rowsAffected = ps.executeUpdate();
            
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Borrower (ID: " + borrowerId + ") updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                
                // 🔥 LOGGING ADDED 🔥
                ActivityLog.log("BORROWER_UPDATED", 
                    String.format("Updated Borrower ID: %d, New Name: %s, New Contact: %s", borrowerId, name, contact));
                
                parentPanel.loadBorrowers(null);  // Refresh the main panel table
                this.dispose();              // Close this form
            } else {
                 JOptionPane.showMessageDialog(this, "No changes made or borrower not found.", "Warning", JOptionPane.WARNING_MESSAGE);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error during update: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_updateborrowerActionPerformed

