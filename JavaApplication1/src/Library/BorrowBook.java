    // Helper to calculate and set the due date fields
    private void setDueDate(int days) {
        LocalDateTime now = LocalDateTime.now();
        LocalDateTime returnDate = now.plusDays(days);
        
        DateTimeFormatter dateFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd");
        DateTimeFormatter timeFormatter = DateTimeFormatter.ofPattern("HH:mm:ss");
        
        jTextField6.setText(returnDate.format(dateFormatter)); // Date field (jTextField6)
        jTextField7.setText(returnDate.format(timeFormatter)); // Time field (jTextField7)
    }

    // 🔥 NEW FUNCTION: Resets the Borrower ID and due dates 🔥
    private void resetForm() {
        // Reset Borrower ID field
        jTextField1.setText(BORROWER_ID_DEFAULT);
        
        // Reset Due Date (default 7 days)
        setDueDate(7);
    }
    
    // 🔥 NEW FUNCTION: Sets up placeholder behavior for Borrower ID field 🔥
    private void setupBorrowerIdFocus() {
        jTextField1.addFocusListener(new FocusListener() {
            @Override
            public void focusGained(FocusEvent e) {
                if (jTextField1.getText().equals(BORROWER_ID_DEFAULT)) {
                    jTextField1.setText("");
                }
            }

            @Override
            public void focusLost(FocusEvent e) {
                if (jTextField1.getText().isEmpty()) {
                    jTextField1.setText(BORROWER_ID_DEFAULT);
                }
            }
        });
    }

