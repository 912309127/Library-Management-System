    // Method to load data for update mode
    private void loadBorrowerData(int id) {
        String sql = "SELECT name, address, contact FROM borrowers WHERE borrower_id = ?";
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            
            ps.setInt(1, id);
            
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    // Populate fields with existing data using auto-generated names
                    jTextField1.setText(rs.getString("name"));
                    jTextField2.setText(rs.getString("address"));
                    jTextField3.setText(rs.getString("contact"));
                } else {
                    JOptionPane.showMessageDialog(this, "Borrower ID not found.", "Error", JOptionPane.ERROR_MESSAGE);
                    this.dispose();
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading borrower data: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
            this.dispose();
        }
    }
    
