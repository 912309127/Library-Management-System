    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
    String title = jTextField1.getText().trim(); 
        String author = jTextField2.getText().trim(); 
        String genre = jTextField3.getText().trim(); 
        String barcode = jTextField4.getText().trim(); 

        if (title.isEmpty() || author.isEmpty() || genre.isEmpty() || barcode.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try (Connection conn = DBConnection.getConnection()) {
            // 1. Check for duplicate barcode (excluding the current book's ID)
            String checkSql = "SELECT book_id FROM books WHERE barcode=? AND book_id<>?";
            try (PreparedStatement psCheck = conn.prepareStatement(checkSql)) {
                psCheck.setString(1, barcode);
                psCheck.setInt(2, bookId);
                try (ResultSet rs = psCheck.executeQuery()) {
                    if (rs.next()) {
                        JOptionPane.showMessageDialog(this, "Invalid: Barcode already exists!", "Duplicate Entry", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                }
            }

            // 2. Perform the update
            String updateSql = "UPDATE books SET title=?, author=?, genre=?, barcode=? WHERE book_id=?";
            try (PreparedStatement ps = conn.prepareStatement(updateSql)) {
                ps.setString(1, title);
                ps.setString(2, author);
                ps.setString(3, genre);
                ps.setString(4, barcode);
                ps.setInt(5, bookId);
                ps.executeUpdate();

                JOptionPane.showMessageDialog(this, "Book updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                
                // LOGGING ADDED
                ActivityLog.log("BOOK_UPDATED", 
                    String.format("Updated Book ID: %d, New Title: %s, New Barcode: %s", bookId, title, barcode));
                
                parent.loadBooks();  // Refresh the main table
                this.dispose();      // Close this frame
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_updateActionPerformed

