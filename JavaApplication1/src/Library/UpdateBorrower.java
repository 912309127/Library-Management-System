    // ADDED: Logic to fetch existing data from the database
    private void loadBorrowerData() {
        String sql = "SELECT name, address, contact FROM borrowers WHERE borrower_id = ?";
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            
            ps.setInt(1, borrowerId);
            
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    // Populate fields using auto-generated names
                    jTextField1.setText(rs.getString("name"));
                    jTextField2.setText(rs.getString("address"));
                    jTextField3.setText(rs.getString("contact"));
                } else {
                    JOptionPane.showMessageDialog(this, "Borrower ID not found. Cannot load data.", "Error", JOptionPane.ERROR_MESSAGE);
                    this.dispose();
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading borrower data: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
            this.dispose();
        }
    }

