    private void submitborrowerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitborrowerActionPerformed
    String name = jTextField1.getText().trim();
    String address = jTextField2.getText().trim();
    String contact = jTextField3.getText().trim();

    // 1. Validation
    if (name.isEmpty() || address.isEmpty() || contact.isEmpty() || 
        name.equals("Name") || address.equals("Address") || contact.equals("Contact #")) {
        JOptionPane.showMessageDialog(this, "Please fill all fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    String sql;
    String successMessage;
    String logType;
    String logDescription;
    
    if (borrowerId == -1) {
        // INSERT Mode
        // Use RETURN_GENERATED_KEYS to retrieve the new ID for logging
        sql = "INSERT INTO borrowers (name, address, contact, status) VALUES (?, ?, ?, 'Active')";
        successMessage = "New Borrower added successfully!";
        logType = "BORROWER_ADDED";
        logDescription = String.format("Added new Borrower: %s (Contact: %s)", name, contact);
    } else {
        // UPDATE Mode
        sql = "UPDATE borrowers SET name=?, address=?, contact=? WHERE borrower_id=?";
        successMessage = "Borrower updated successfully!";
        logType = "BORROWER_UPDATED";
        logDescription = String.format("Updated Borrower ID: %d, Name: %s", borrowerId, name);
    }

    // 2. Database Operation
    try (Connection conn = DBConnection.getConnection();
         // Use Statement.RETURN_GENERATED_KEYS only for INSERT, otherwise just a standard statement
         PreparedStatement ps = (borrowerId == -1) ? 
                                conn.prepareStatement(sql, java.sql.Statement.RETURN_GENERATED_KEYS) : 
                                conn.prepareStatement(sql)) {
        
        ps.setString(1, name);
        ps.setString(2, address);
        ps.setString(3, contact);

        if (borrowerId != -1) {
            // If in UPDATE mode, set the WHERE clause parameter
            ps.setInt(4, borrowerId);
        }
        
        ps.executeUpdate();
        
        // Handle getting the new ID for the log if in ADD mode
        if (borrowerId == -1) {
             try(ResultSet generatedKeys = ps.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    borrowerId = generatedKeys.getInt(1); // Get the new ID
                    // Update the log description to include the ID
                    logDescription = String.format("Added new Borrower ID: %d, Name: %s (Contact: %s)", borrowerId, name, contact);
                }
            }
        }
        
        JOptionPane.showMessageDialog(this, successMessage, "Success", JOptionPane.INFORMATION_MESSAGE);
        
        // 🔥 LOGGING ADDED 🔥
        ActivityLog.log(logType, logDescription);
        
        parentPanel.loadBorrowers(null); // Refresh the main panel
        this.dispose();              // Close this form

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
    }//GEN-LAST:event_submitborrowerActionPerformed

