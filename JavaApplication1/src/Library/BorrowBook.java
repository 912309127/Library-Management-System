    private void submitborrowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitborrowActionPerformed
    String borrowerIdText = jTextField1.getText().trim();
    String borrowDate = jTextField5.getText().trim(); 
    // Concatenate Date (jTextField6) and Time (jTextField7) fields
    String dueDate = jTextField6.getText().trim() + " " + jTextField7.getText().trim();

    // 1. Basic Input Validation (Empty/Placeholder)
    if (borrowerIdText.isEmpty() || borrowerIdText.equals("Borrower's ID")) {
        JOptionPane.showMessageDialog(this, "Please enter the Borrower's ID.", "Input Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    int borrowerId;
    try {
        // 2. Numeric Input Validation
        borrowerId = Integer.parseInt(borrowerIdText);

        // =================================================================
        // 3. CHECK BORROWER EXISTENCE AND STATUS (PREVENTS FOREIGN KEY ERROR)
        // =================================================================
        String checkBorrowerSql = "SELECT status FROM borrowers WHERE borrower_id = ?";
        String borrowerStatus = null;
        
        try (Connection conn = DBConnection.getConnection();
             PreparedStatement psCheck = conn.prepareStatement(checkBorrowerSql)) {
            
            psCheck.setInt(1, borrowerId);
            try (ResultSet rs = psCheck.executeQuery()) {
                if (rs.next()) {
                    borrowerStatus = rs.getString("status");
                }
            }
        } catch (SQLException e) {
            // Stop on database error during the check
            JOptionPane.showMessageDialog(this, 
                "Database error during borrower check: " + e.getMessage(), 
                "DB Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
            return;
        }

        if (borrowerStatus == null) {
            // 🔥 This is the desired message when borrower ID is missing 🔥
            JOptionPane.showMessageDialog(this, 
                "Borrower ID " + borrowerId + " does not exist in the database.\n" +
                "Please add the borrower using the 'Borrowinfo' panel first.", 
                "Validation Failed: Borrower Not Found", JOptionPane.ERROR_MESSAGE);
            return; // STOP: Prevents the foreign key error
        }
        
        if (!borrowerStatus.equalsIgnoreCase("Active")) {
            // Stop if borrower is inactive
            JOptionPane.showMessageDialog(this, 
                "Borrower ID " + borrowerId + " is currently " + borrowerStatus + " and cannot borrow books.", 
                "Validation Failed: Inactive Borrower", JOptionPane.ERROR_MESSAGE);
            return; 
        }
        // =================================================================
        // END VALIDATION
        // =================================================================


        // 4. Execute Loan Transaction (Only runs if all validation passed)
        String insertSql = "INSERT INTO transactions (book_id, borrower_id, borrow_date, due_date, status) VALUES (?, ?, ?, ?, 'Borrowed')";
        String updateBookSql = "UPDATE books SET status='Borrowed' WHERE book_id=?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement psInsert = conn.prepareStatement(insertSql);
             PreparedStatement psUpdate = conn.prepareStatement(updateBookSql))
        {
            // Transaction INSERT
            psInsert.setInt(1, this.bookId);
            psInsert.setInt(2, borrowerId);
            psInsert.setString(3, borrowDate);
            psInsert.setString(4, dueDate);
            psInsert.executeUpdate();

            // Book Status UPDATE
            psUpdate.setInt(1, this.bookId);
            psUpdate.executeUpdate();

            JOptionPane.showMessageDialog(this, 
                "Book '" + bookTitle + "' successfully borrowed by Borrower ID " + borrowerId + ".", 
                "Success", JOptionPane.INFORMATION_MESSAGE);
            
            ActivityLog.log("BOOK_BORROWED", 
                String.format("Borrowed Book ID: %d (%s) to Borrower ID: %d. Due: %s.", 
                              this.bookId, this.bookTitle, borrowerId, dueDate));

            // Refresh the parent table and close
            this.parentPanel.loadBooks();
            this.dispose();

        } catch (SQLException e) {
            // Catch error during the actual transaction (e.g., connection lost)
            JOptionPane.showMessageDialog(this, 
                "Database error during borrow transaction: " + e.getMessage(), 
                "DB Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }

    } catch (NumberFormatException e) {
        // Catch block for invalid numeric input
        JOptionPane.showMessageDialog(this, "Borrower's ID must be a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_submitborrowActionPerformed

