    private void addFocusListeners() {
        // IMPORTANT: Use the actual generated variable names!
        JTextField[] fields = {jTextField1, jTextField2, jTextField3, jTextField4};
        final String[] defaultTexts = {"Title", "Author", "Genre", "Barcode"};

        for (int i = 0; i < fields.length; i++) {
            JTextField field = fields[i];
            final String defaultText = defaultTexts[i];

            field.addFocusListener(new FocusListener() {
                @Override
                public void focusGained(FocusEvent e) {
                    if (field.getText().equals(defaultText)) {
                        field.setText("");
                    }
                }

                @Override
                public void focusLost(FocusEvent e) {
                    if (field.getText().isEmpty()) {
                        field.setText(defaultText);
                    }
                }
            });
        }
    }

